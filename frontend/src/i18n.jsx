const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem("pdd_lang") || "id");
  useEffect(() => {
    localStorage.setItem("pdd_lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);
  const t = (key) => dict[lang][key] ?? dict.id[key] ?? key;
  const pick = (obj, base) => {
    if (!obj) return { value: "", fallback: false };
    const en = obj[`${base}_en`];
    const id = obj[`${base}_id`];
    if (lang === "en" && en) return { value: en, fallback: false };
    if (lang === "en" && !en) return { value: id || "", fallback: true };
    return { value: id || "", fallback: false };
  };
  return (
    <LangContext.Provider value={{ lang, setLang, t, pick }}>{children}</LangContext.Provider>
  );
}

export const useLang = () => useContext(LangContext);
